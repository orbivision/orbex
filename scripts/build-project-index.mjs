#!/usr/bin/env node
// Regenerate projects/README.md from the frontmatter in each projects/ORBI-N/plan.md.
//
// The index is DERIVED. Never hand-edit projects/README.md — edit the frontmatter in
// the plan itself and re-run this. That's the whole point: status lives inside the
// artifact it describes, so it can't drift from it.
//
//   node scripts/build-project-index.mjs          # write projects/README.md
//   node scripts/build-project-index.mjs --check  # exit 1 if out of date (no write)
//   node scripts/build-project-index.mjs --json   # every project as JSON on stdout (no write)
//
// --json exists for scripts/dashboard.mjs (ORBI-86), which needs DONE projects too — next.mjs
// only lists open ones. The dashboard renders this; it never reads a plan itself.
//
// Dependency-free on purpose: this repo has no package.json and shouldn't need one.

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { resolveWorkspace, projectKey, projectDirRe } from './lib/workspace.mjs';

const { root: REPO } = resolveWorkspace();
const KEY = projectKey(REPO);
if (KEY.error) { console.error(`build-project-index.mjs: ${KEY.error}`); process.exit(1); }
const PROJECT_DIR = projectDirRe(KEY.key);
const PROJECTS = path.join(REPO, 'projects');
const OUT = path.join(PROJECTS, 'README.md');

// Order matters — it's the display order of the "in flight" grouping.
const OPEN_STATUSES = ['blocked', 'active', 'open'];
const ALL_STATUSES = [...OPEN_STATUSES, 'done', 'dropped'];
const PRIORITY_RANK = { high: 0, medium: 1, low: 2, undefined: 3 };

// Minimal frontmatter reader. Supports `key: value` and `key: [a, b]`; that's all the
// schema uses, and a YAML dependency would be a poor trade for it.
function readFrontmatter(src) {
  if (!src.startsWith('---\n')) return null;
  const end = src.indexOf('\n---', 4);
  if (end === -1) return null;
  const out = {};
  for (const line of src.slice(4, end).split('\n')) {
    const m = line.match(/^([a-z_]+):\s*(.*)$/);
    if (!m) continue;
    const [, key, raw] = m;
    out[key] = raw.startsWith('[')
      ? raw.replace(/^\[|\]$/g, '').split(',').map((s) => s.trim()).filter(Boolean)
      : raw.trim();
  }
  return out;
}

function loadProjects() {
  const dirs = readdirSync(PROJECTS, { withFileTypes: true })
    .filter((d) => d.isDirectory() && PROJECT_DIR.test(d.name))
    .map((d) => d.name)
    .sort((a, b) => Number(b.split('-')[1]) - Number(a.split('-')[1]));

  const projects = [];
  const problems = [];

  for (const id of dirs) {
    const dir = path.join(PROJECTS, id);
    // ORBI-23 is a research spike with no plan.md — recommendation.md is its artifact.
    const name = ['plan.md', 'recommendation.md'].find((f) => existsSync(path.join(dir, f)));
    if (!name) { problems.push(`${id}: no plan.md or recommendation.md`); continue; }

    const src = readFileSync(path.join(dir, name), 'utf8');
    const fm = readFrontmatter(src);
    if (!fm) { problems.push(`${id}: no frontmatter`); continue; }
    if (!ALL_STATUSES.includes(fm.status)) {
      problems.push(`${id}: status "${fm.status ?? '(missing)'}" is not one of ${ALL_STATUSES.join(', ')}`);
    }

    const heading = src.slice(src.indexOf('\n---', 4)).match(/^#\s+(.+)$/m);
    const title = (heading?.[1] ?? id).replace(new RegExp(`^${id}\\s*[:—-]\\s*`), '');

    projects.push({ id, num: Number(id.split('-')[1]), file: `${id}/${name}`, title, ...fm });
  }
  return { projects, problems };
}

function esc(s) {
  return String(s ?? '').replace(/\|/g, '\\|');
}

function row(p) {
  const extra = [p.epic && `epic ${p.epic}`, p.priority && `**${p.priority}**`]
    .filter(Boolean).join(', ');
  return `| [${p.id}](${p.file}) | ${esc(p.title)} | ${p.status} | ${p.opened ?? '—'} | ${p.closed ?? '—'} | ${esc(extra) || '—'} |`;
}

function build({ projects, problems }) {
  const open = projects
    .filter((p) => OPEN_STATUSES.includes(p.status))
    .sort((a, b) =>
      OPEN_STATUSES.indexOf(a.status) - OPEN_STATUSES.indexOf(b.status) ||
      PRIORITY_RANK[a.priority] - PRIORITY_RANK[b.priority] ||
      a.num - b.num);

  const counts = ALL_STATUSES
    .map((s) => [s, projects.filter((p) => p.status === s).length])
    .filter(([, n]) => n > 0);

  const L = [];
  L.push('# Projects');
  L.push('');
  L.push('<!-- GENERATED by scripts/build-project-index.mjs — do not edit by hand.');
  L.push('     Change the frontmatter in the plan itself, then re-run the script. -->');
  L.push('');
  L.push(`**${projects.length} projects** — ` + counts.map(([s, n]) => `${n} ${s}`).join(', ') + '.');
  L.push('');
  L.push('For work that isn\'t a numbered project yet, see [`../BACKLOG.md`](../BACKLOG.md).');
  L.push('Run `/o-next` to get everything still open across projects, backlog, and the GitHub');
  L.push('Issues inbox in one prioritized list.');
  L.push('');

  L.push('## In flight');
  L.push('');
  if (open.length === 0) {
    L.push('Nothing open. Every numbered project is closed out.');
  } else {
    L.push('| # | Title | Status | Opened | Closed | Notes |');
    L.push('|---|---|---|---|---|---|');
    open.forEach((p) => L.push(row(p)));
  }
  L.push('');

  L.push('## All projects');
  L.push('');
  L.push('Newest first.');
  L.push('');
  L.push('| # | Title | Status | Opened | Closed | Notes |');
  L.push('|---|---|---|---|---|---|');
  projects.forEach((p) => L.push(row(p)));
  L.push('');

  if (problems.length) {
    L.push('## Problems found while generating');
    L.push('');
    problems.forEach((p) => L.push(`- ${p}`));
    L.push('');
  }
  return L.join('\n');
}

const data = loadProjects();

if (process.argv.includes('--json')) {
  // `file` is relative to projects/ in the markdown index; make it workspace-relative here so
  // a consumer needn't know that.
  const projects = data.projects.map((p) => ({ ...p, file: `projects/${p.file}` }));
  process.stdout.write(JSON.stringify({ key: KEY.key, projects, problems: data.problems }, null, 2) + '\n');
  process.exit(0);
}

const content = build(data);

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== content) {
    console.error('projects/README.md is out of date — run: node scripts/build-project-index.mjs');
    process.exit(1);
  }
  console.log('projects/README.md is up to date.');
} else {
  writeFileSync(OUT, content);
  console.log(`wrote ${path.relative(REPO, OUT)} — ${data.projects.length} projects`);
  data.problems.forEach((p) => console.warn(`  warning: ${p}`));
}
